// ─────────────────────────────────────────────────────────────────────────────
//  API Client — communicates with Cloudflare Pages Functions
//  Coach, metrics, and classification logic lives server-side.
//  Share encoding/decoding is done entirely client-side (no server roundtrip).
// ─────────────────────────────────────────────────────────────────────────────
import { encodeGameHash, decodeGameHash } from './shareEncoder.js';
import { calculateAllMetrics } from './metricsCalculator.js';
import { classifyMove } from './moveClassifier.js';

const API_BASE = '/api';

async function post(endpoint, body) {
  const res = await fetch(`${API_BASE}${endpoint}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  });

  if (!res.ok) {
    const err = await res.json().catch(() => ({ error: res.statusText }));
    throw new Error(err.error || `API error ${res.status}`);
  }

  return res.json();
}

// ── Coach Explanation (Server-side) ─────────────────────────────────────────────
// Explanations are generated by the server backend via the analyze endpoint.

export async function fetchExplanation(params) {
  return post('/analyze', params);
}

// ── Share Link Encoding (client-side, no server call) ───────────────────────
/**
 * Encode a completed analysis into a shareable hash string.
 * Runs entirely in the browser — instant, no network, no failure modes.
 *
 * @param {object} params
 * @param {Array}  params.analysisResults – array of analyzed move objects
 * @param {string} params.pgnVariant      – 'standard' or 'chess960'
 * @param {string} [params.startingFen]   – starting FEN for Chess960
 * @param {object} [params.gameInfo]      – { white, black } player names
 * @returns {Promise<{hash: string}>}
 */
export async function shareGame({ analysisResults, pgnVariant, startingFen, gameInfo, theme, pieceSet, metrics, fromMoveIndex, perspective }) {
  const hash = encodeGameHash(analysisResults, pgnVariant, startingFen, gameInfo, { theme, pieceSet, metrics, fromMoveIndex, perspective });
  return { hash };
}

// ── Share Link Decoding (client-side, no server call) ───────────────────────
/**
 * Decode a shared game hash string back into analysis data.
 * Runs entirely in the browser — instant, no network, no failure modes.
 *
 * @param {string} hashString – the encoded hash from the URL
 * @returns {Promise<{results, positions, finalFen, pgnVariant, startingFen, white, black}>}
 */
export async function loadSharedGame(hashString) {
  return decodeGameHash(hashString);
}

// ── Metrics & Accuracy ──────────────────────────────────────────────────────
/**
 * Fetch move classifications in batch from the server.
 * @param {Array} movesData 
 * @returns {Promise<Array>} array of classification objects
 */
export async function fetchClassifications(movesData) {
  try {
    const res = await post('/metrics', { action: 'classifyMoves', payload: { movesData } });
    return res.classifications;
  } catch (err) {
    console.warn('[Metrics] API unreachable, classifying moves locally:', err.message);
    return movesData.map(data => classifyMove(data));
  }
}

/**
 * Fetch overall game metrics (accuracy, ACPL, counts) from the server.
 * If server is unreachable (local dev or network issue), seamlessly falls back
 * to the exact same client-side calculation to guarantee zero interruption.
 * @param {Array} movesArray 
 * @param {number} whiteRating
 * @param {number} blackRating
 * @returns {Promise<object>}
 */
export async function fetchGameMetrics(movesArray, whiteRating = 1200, blackRating = 1200) {
  try {
    return await post('/metrics', { action: 'calculateMetrics', payload: { movesArray, whiteRating, blackRating } });
  } catch (err) {
    console.warn('[Metrics] API unreachable, computing metrics locally:', err.message);
    return calculateAllMetrics(movesArray, whiteRating, blackRating);
  }
}

